def all_paragraphs(doc):
    """Сите пасуси, вклучувајќи ги и оние во ќелии на табели."""
    yield from doc.paragraphs
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                yield from cell.paragraphs


def apply_tables(doc, pairs, label):
    done, absent = 0, []
    for old, new in pairs:
        hit = False
        for p in all_paragraphs(doc):
            if old not in p.text:
                continue
            target = next((r for r in p.runs if old in r.text), None)
            if target is None:      # текстот е поделен низ повеќе runs
                merged = p.text.replace(old, new)
                for r in p.runs[1:]:
                    r._element.getparent().remove(r._element)
                if p.runs:
                    p.runs[0].text = merged
            else:
                target.text = target.text.replace(old, new)
            done += 1
            hit = True
            break
        if not hit:
            absent.append(old[:52])
    print(f"{label}: {done}/{len(pairs)} применети")
    for a in absent:
        print(f"   НЕ Е НАЈДЕНО: {a}…")
    return done


def apply(doc, pairs, label):
    done, spanning, absent = 0, [], []
    for old, new in pairs:
        found = False
        for p in doc.paragraphs:
            if old not in p.text:
                continue
            found = True
            target = next((r for r in p.runs if old in r.text), None)
            if target is None:
                spanning.append(old[:60])
                break
            target.text = target.text.replace(old, new)
            done += 1
            break
        if not found:
            absent.append(old[:60])
    print(f"{label}: {done}/{len(pairs)} применети")
    for s in spanning:
        print(f"   ПРЕСКОКНАТО (низ повеќе runs): {s}…")
    for a in absent:
        print(f"   НЕ Е НАЈДЕНО: {a}…")
    return done


def main():
    dry = "--dry-run" in sys.argv
    doc = Document(str(SRC))
    n = apply(doc, TERMS, "Терминолошки замени")
    n += apply(doc, SENTENCES, "Преработени реченици")
    n += apply_tables(doc, TABLES, "Замени во табели")

    # 8.1 е потпоглавје, а носи стил на поглавје
    for p in doc.paragraphs:
        if re.sub(r"\s+", " ", p.text).strip().startswith("8.1 Одговори") \
                and p.style.name == "Heading 1":
            p.style = doc.styles["Heading 2"]
            print("Поправен стил: 8.1 Heading 1 -> Heading 2")
            n += 1
            break

    if dry:
        print(f"\n[dry-run] вкупно {n} измени, датотеката не е зачувана")
        return 0
    doc.save(str(OUT))
    print(f"\nвкупно {n} измени зачувани во {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
